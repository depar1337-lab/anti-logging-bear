# Anti-Logging Bear by Priest

from __future__ import annotations

import io
import zipfile

import pytest

from antiloggingbear.engine import Severity, forge

yara = pytest.importorskip("yara")

RULES = '''import "pe"
import "hash"

rule MAL_Fake_Stealer_A {
    meta:
        description = "Fake stealer used in Barry's tests"
        score = 80
    strings:
        $a = "BARRY-TEST-STEALER"
    condition:
        $a
}

rule HKTL_Fake_Injector {
    meta:
        description = "Fake injector"
    strings:
        $a = "BARRY-TEST-INJECTOR"
    condition:
        $a
}

rule SUSP_Hash_Based {
    condition:
        hash.md5(0, filesize) == "00000000000000000000000000000000"
}

private rule Needs_Hash {
    condition:
        hash.sha256(0, 4) == "x"
}

rule MAL_Depends_On_Private {
    strings:
        $a = "BARRY-TEST-PRIVATE"
    condition:
        $a and Needs_Hash
}
'''


def zipped(name: str, text: str) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr(f"packages/{name}/yara-rules-{name}.yar", text)
    return buffer.getvalue()


def bundle():
    core = RULES.split("rule HKTL_Fake_Injector")[0]
    return forge.read_bundle(forge.build_bundle(zipped("full", RULES), zipped("core", core), "20991231"))


class NoHashYara:
    Error = yara.Error
    SyntaxError = yara.SyntaxError
    __version__ = "test"

    @staticmethod
    def compile(source):
        if 'import "hash"' in source:
            raise yara.SyntaxError('line 2: unknown module "hash"')
        return yara.compile(source=source)

    load = staticmethod(yara.load)


def test_bundle_round_trip():
    loaded = bundle()
    assert loaded.release == "20991231"
    assert "MAL_Fake_Stealer_A" in loaded.core
    assert "HKTL_Fake_Injector" not in loaded.core


def test_compiles_without_a_missing_module(tmp_path):
    rules, count = forge.compile_bundle(NoHashYara, bundle(), tmp_path)
    assert count == 2
    matched = {m.rule for m in rules.match(data=b"BARRY-TEST-STEALER BARRY-TEST-INJECTOR BARRY-TEST-PRIVATE")}
    assert matched == {"MAL_Fake_Stealer_A", "HKTL_Fake_Injector"}
    again, cached = forge.compile_bundle(NoHashYara, bundle(), tmp_path)
    assert cached == 2


def test_grading():
    core = bundle().core
    severity, title, kind = forge.grade("MAL_Fake_Stealer_A", {"description": "Fake stealer"}, core)
    assert severity is Severity.CRITICAL and kind == "malware"
    severity, _title, kind = forge.grade("MAL_Something_Else", {"description": "x"}, core)
    assert severity is Severity.HIGH
    severity, _title, kind = forge.grade("HKTL_Fake_Injector", {"description": "Fake injector"}, core)
    assert severity is Severity.MEDIUM and kind == "tool"
    _severity, title, _kind = forge.grade(
        "MALPEDIA_Win_Redline_Auto",
        {"description": "autogenerated rule brought to you by yara-signator",
         "reference": "https://malpedia.caad.fkie.fraunhofer.de/details/win.redline_stealer"}, core)
    assert title == "Matches known malware: Redline Stealer (Windows)"
